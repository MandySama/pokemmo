/** 角色选择封包的 ID 签名混合函数。 */
public final class CharacterSignature {
    /** 固定的整数混合，不依赖本地库。 */
    public static long sigHash(int input) {
        long rcx, rdx, r9, r10;
        long r8 = Integer.toUnsignedLong(Integer.reverseBytes(input));
        long rax = r8;
        rcx = 0x0400000000000000L;
        rax |= rcx;
        r8 = 0x9482AF40BDB7FC01L;
        rcx = 0x1D43A62738FC3273L;
        r10 = rax;
        r10 ^= rcx;
        r9 = 0xA5AC9598BED7D011L;
        r9 += r10;
        rcx = 0x01FF35BEA85FA125L;
        r10 = Long.rotateRight(r10, 48);
        rdx = 0xD0ADFF72C8044FBCL;
        r10 ^= r9;
        r9 -= rcx;
        rdx += r10;
        rcx = r9;
        rcx ^= r8;
        r10 = Long.rotateRight(r10, 43);
        r10 ^= rdx;
        r9 = Long.rotateRight(r9, 32);
        rdx += rcx;
        r9 += r10;
        rcx = Long.rotateRight(rcx, 51);
        rcx ^= rdx;
        r10 = Long.rotateRight(r10, 48);
        r10 ^= r9;
        rdx = Long.rotateRight(rdx, 32);
        r9 += rcx;
        rdx += r10;
        rcx = Long.rotateRight(rcx, 47);
        rcx ^= r9;
        r10 = Long.rotateRight(r10, 43);
        r10 ^= rdx;
        r9 = Long.rotateRight(r9, 32);
        rdx ^= rax;
        r9 ^= 0x00000000000000FFL;
        rdx += rcx;
        r9 += r10;
        rcx = Long.rotateRight(rcx, 51);
        rcx ^= rdx;
        r10 = Long.rotateRight(r10, 48);
        r10 ^= r9;
        rdx = Long.rotateRight(rdx, 32);
        r9 += rcx;
        rdx += r10;
        rcx = Long.rotateRight(rcx, 47);
        rcx ^= r9;
        r10 = Long.rotateRight(r10, 43);
        r10 ^= rdx;
        r9 = Long.rotateRight(r9, 32);
        rdx += rcx;
        r9 += r10;
        rcx = Long.rotateRight(rcx, 51);
        rcx ^= rdx;
        r10 = Long.rotateRight(r10, 48);
        r10 ^= r9;
        rdx = Long.rotateRight(rdx, 32);
        r9 += rcx;
        rdx += r10;
        rcx = Long.rotateRight(rcx, 47);
        rcx ^= r9;
        r10 = Long.rotateRight(r10, 43);
        r10 ^= rdx;
        r9 = Long.rotateRight(r9, 32);
        rdx += rcx;
        r9 += r10;
        rcx = Long.rotateRight(rcx, 51);
        rcx ^= rdx;
        r10 = Long.rotateRight(r10, 48);
        r10 ^= r9;
        rdx = Long.rotateRight(rdx, 32);
        r9 += rcx;
        rdx += r10;
        rcx = Long.rotateRight(rcx, 47);
        rcx ^= r9;
        r10 = Long.rotateRight(r10, 43);
        r10 ^= rdx;
        r9 = Long.rotateRight(r9, 32);
        r9 += r10;
        r8 = rcx;
        rax = rdx + rcx;
        r8 = Long.rotateRight(r8, 51);
        r8 ^= rax;
        r10 = Long.rotateRight(r10, 48);
        r10 ^= r9;
        r10 = Long.rotateRight(r10, 43);
        rdx = r8 + r9;
        r8 = Long.rotateRight(r8, 47);
        rax = rdx;
        rax = Long.rotateRight(rax, 32);
        rax ^= r10;
        rax ^= r8;
        rax ^= rdx;
        return rax;
    }
}
