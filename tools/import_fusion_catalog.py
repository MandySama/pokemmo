"""导入 PIF 全部双宝可梦自定义融合及替代版本的目录，图片由客户端按需缓存。"""
import csv,gzip,hashlib,io,json,pathlib,re,urllib.request,unicodedata
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'data/cosmetics/pokemon';OUT.mkdir(parents=True,exist_ok=True)
URLS={
 'sprites':'https://raw.githubusercontent.com/infinitefusion/pif-downloadables/master/CUSTOM_SPRITES',
 'credits':'https://infinitefusion.net/customsprites/Sprite_Credits.csv',
 'species':'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv',
 'mapping':'https://infinitefusion.fandom.com/api.php?action=parse&page=Pok%C3%A9dex%2FHoenn%2FClassic&prop=wikitext&format=json'}
def fetch(url):
 request=urllib.request.Request(url,headers={'User-Agent':'Pokemon-cosmetics-catalog-import/1.0'})
 with urllib.request.urlopen(request,timeout=60) as result:return result.read()
def normalize(text):
 text=re.sub(r'\([^)]*\)','',text).strip().lower().replace('♀','-f').replace('♂','-m')
 text=unicodedata.normalize('NFKD',text).encode('ascii','ignore').decode()
 return re.sub(r'[^a-z0-9]+','',text)
raw={name:fetch(url) for name,url in URLS.items()}
national={normalize(row['identifier']):int(row['id']) for row in csv.DictReader(io.StringIO(raw['species'].decode())) if int(row['id'])<=1025}
wiki=json.loads(raw['mapping'])['parse']['wikitext']['*']
rows=re.findall(r'\{\{PokedexTable/Data\|(\d+)\|(\d+)\|([^|]+)\|([^|]*)\|',wiki)
mapping={};unmapped=[]
for _,pif,name,form in rows:
 key=normalize(name);key={'nidoranfemale':'nidoranf','nidoranmale':'nidoranm'}.get(key,key)
 if key not in national:unmapped.append((pif,name,form));continue
 mapping[int(pif)]=(national[key],name.strip(),form.strip())
if unmapped:raise ValueError(('Unmapped species',unmapped))
credits={row[0]:row[1].strip() for row in csv.reader(io.StringIO(raw['credits'].decode('utf-8-sig'))) if len(row)>1}
items=[];skipped=[]
for file in raw['sprites'].decode().splitlines():
 match=re.fullmatch(r'(\d+)\.(\d+)([a-z]*)\.png',file)
 if not match:skipped.append(file);continue
 head,body=int(match[1]),int(match[2]);key=file[:-4]
 if head not in mapping or body not in mapping:raise ValueError(('Unknown PIF index',file))
 artist=re.sub(r'[\t\r\n]+',' ',credits.get(key,''))
 items.append((key,mapping[head][0],mapping[body][0],1,artist))
items.sort(key=lambda row:tuple(map(int,re.match(r'(\d+)\.(\d+)',row[0]).groups()))+(re.sub(r'^[0-9.]+','',row[0]),))
content='# id\tnational head\tnational body\tpixel scale\tartist\n'+''.join('\t'.join(map(str,row))+'\n' for row in items)
(OUT/'fusion-catalog.tsv.gz').write_bytes(gzip.compress(content.encode(),mtime=0))
(OUT/'fusion-species.tsv').write_text('# PIF id\tnational id\tname\tform\n'+''.join(f'{i}\t{n}\t{name}\t{form}\n' for i,(n,name,form) in sorted(mapping.items())),encoding='utf-8')
manifest={'count':len(items),'species':len(mapping),'scope':'All two-Pokemon custom fusion PNG entries including alternate sprites; source contains one triple fusion outside the A+B costume format. Autogenerated pairs without custom art are not fabricated.','skipped':skipped,'sources':{name:{'url':url,'sha256':hashlib.sha256(raw[name]).hexdigest()} for name,url in URLS.items()},'sheet_url':'https://infinitefusion.net/customsprites/spritesheets/spritesheets_custom/{head}/{head}{alt}.png','sheet_tile_size':96,'sheet_columns':20,'license':'Author credits retained; no general redistribution license verified.'}
(OUT/'fusion-sources.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'costumes':len(items),'PIF_species':len(mapping),'national_species':len(set(row[0] for row in mapping.values())),'sample_255':mapping.get(255),'last':mapping.get(582)},ensure_ascii=False))
